"""Ingestion summary: what landed, per endpoint and season, from the manifest and raw files. Offline."""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

import polars as pl

from cfb.config import Settings
from cfb.ingest import raw_store
from cfb.ingest.manifest import Manifest
from cfb.ingest.registry import ENDPOINTS
from cfb.ingest.schema_check import MODEL_BY_SLUG, compare


def _season(row: dict) -> int | None:
    m = re.search(r"season=(\d{4})", row["file_path"] or "")
    if m:
        return int(m.group(1))
    year = json.loads(row["params"]).get("year")
    return int(year) if year is not None else None


def landed_requests(settings: Settings) -> pl.DataFrame:
    """Latest manifest row per landed canonical file (diagnostics and /info excluded)."""
    df = Manifest(settings.paths).read()
    df = df.filter(pl.col("file_path").is_not_null() & ~pl.col("file_path").str.contains("/_probe/"))
    df = df.sort("requested_at").unique("file_path", keep="last")
    return df.with_columns(pl.Series("season", [_season(r) for r in df.iter_rows(named=True)], dtype=pl.Int32))


def schema_issues(settings: Settings, slugs: set[str] | None = None) -> dict[str, dict]:
    """Per endpoint: files checked, files with differences, and the union of differences."""
    out: dict[str, dict] = defaultdict(lambda: {"files": 0, "bad": 0, "issues": set()})
    for path in sorted(settings.paths.raw.glob(f"*/**/{raw_store.RESPONSE_FILE}")):
        slug = path.relative_to(settings.paths.raw).parts[0]
        if slug.startswith("_") or slug not in MODEL_BY_SLUG or (slugs and slug not in slugs):
            continue
        payload = raw_store.read_json(path)
        if not payload:
            continue
        diff = compare(payload, MODEL_BY_SLUG[slug])
        out[slug]["files"] += 1
        if not diff.clean:
            out[slug]["bad"] += 1
            out[slug]["issues"].update(f"missing {f}" for f in diff.missing)
            out[slug]["issues"].update(f"extra {f}" for f in diff.extra)
            out[slug]["issues"].update(f"null {f}" for f in diff.null_violations)
            out[slug]["issues"].update(f"{f}: {t}" for f, t in diff.type_mismatches.items())
    return out


def build_summary(settings: Settings, check_schemas: bool = True) -> str:
    manifest = Manifest(settings.paths).read()
    landed = landed_requests(settings)
    data = manifest.filter(pl.col("endpoint") != "info")
    lines = ["# Phase 1b ingestion summary", "",
             "Generated by `cfb ingest summary` from `data/manifest.parquet` and `data/raw`.", ""]

    lines += ["## Calls", "", "| run | requests | counted calls | failures | started | ended |", "|---|---|---|---|---|---|"]
    for r in (data.group_by("run_id")
              .agg(pl.len().alias("n"), pl.col("attempts").sum().alias("calls"),
                   (pl.col("http_status") != 200).fill_null(True).sum().alias("fail"),
                   pl.col("requested_at").min().alias("start"), pl.col("requested_at").max().alias("end"))
              .sort("start").iter_rows(named=True)):
        lines.append(f"| {r['run_id']} | {r['n']} | {r['calls']} | {r['fail']} | {r['start'][:19]} | {r['end'][:19]} |")
    lines += ["", f"Total counted calls: **{int(data['attempts'].sum())}** "
              f"(retries: {int(data['attempts'].sum()) - data.height}).", ""]

    failures = data.filter((pl.col("http_status") != 200) | pl.col("http_status").is_null())
    retried_ok = failures.join(landed.select("endpoint", "params"), on=["endpoint", "params"], how="semi")
    still_failed = failures.join(landed.select("endpoint", "params"), on=["endpoint", "params"], how="anti")
    lines += ["## Failures", "",
              f"{failures.height} failed requests; {retried_ok.height} later landed on a re-run; "
              f"{still_failed.height} still missing.", ""]
    for r in still_failed.iter_rows(named=True):
        lines.append(f"- `{r['endpoint']}` `{r['params']}`: HTTP {r['http_status']} {(r['error'] or '')[:120]}")
    lines.append("")

    lines += ["## Landed, by endpoint", "",
              "| endpoint | files | empty | rows | MB (raw JSON) | truncated pages |", "|---|---|---|---|---|---|"]
    order = [s.slug for s in ENDPOINTS]
    agg = (landed.group_by("endpoint")
           .agg(pl.len().alias("files"), (pl.col("row_count") == 0).sum().alias("empty"),
                pl.col("row_count").sum().alias("rows"), pl.col("bytes").sum().alias("bytes"),
                pl.col("truncated").sum().alias("trunc")))
    by_slug = {r["endpoint"]: r for r in agg.iter_rows(named=True)}
    for slug in order:
        if slug in by_slug:
            r = by_slug[slug]
            lines.append(f"| {slug} | {r['files']} | {r['empty']} | {r['rows']:,} | {r['bytes'] / 1e6:,.1f} | {r['trunc']} |")
    lines.append("")

    seasons = sorted(s for s in landed["season"].unique().to_list() if s is not None)
    pivot = landed.filter(pl.col("season").is_not_null()).group_by("endpoint", "season").agg(pl.col("row_count").sum())
    cells = {(r["endpoint"], r["season"]): r["row_count"] for r in pivot.iter_rows(named=True)}
    lines += ["## Rows by endpoint and season", "",
              "Season = the requested `year` (draft year for `draft_picks`, class year for `recruiting_players`). "
              "`0` = the API returned an empty list; blank = not requested.", "",
              "| endpoint | " + " | ".join(str(s) for s in seasons) + " |",
              "|---|" + "---|" * len(seasons)]
    for slug in order:
        if any((slug, s) in cells for s in seasons):
            lines.append(f"| {slug} | " + " | ".join(f"{cells[(slug, s)]:,}" if (slug, s) in cells else ""
                                                    for s in seasons) + " |")
    lines.append("")

    if check_schemas:
        issues = schema_issues(settings)
        lines += ["## Response shapes vs vendored models (every non-empty file)", "",
                  "| endpoint | files checked | files with differences | differences |", "|---|---|---|---|"]
        for slug in order:
            if slug in issues:
                i = issues[slug]
                lines.append(f"| {slug} | {i['files']} | {i['bad']} | {'; '.join(sorted(i['issues'])) or 'none'} |")
        lines.append("")
    return "\n".join(lines)


def write_summary(settings: Settings, check_schemas: bool = True) -> Path:
    path = settings.paths.reports / "phase1b_ingest.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_summary(settings, check_schemas))
    return path
